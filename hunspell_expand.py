"""Minimal Hunspell dictionary expander ("unmunch") for the Spanish dictionary.

Supports what the RLA-ES Spanish dictionary uses: PFX/SFX rules with strip,
add and condition, single-character flags (FLAG UTF-8), continuation classes
on affixes (e.g. ``ción/S``) and prefix+suffix cross products.
"""
import re
from collections import defaultdict


class Affix:
    __slots__ = ("kind", "flag", "cross", "strip", "add", "cont", "cond")

    def __init__(self, kind, flag, cross, strip, add, cont, cond):
        self.kind = kind
        self.flag = flag
        self.cross = cross
        self.strip = "" if strip == "0" else strip
        self.add = "" if add == "0" else add
        self.cont = cont
        if cond == ".":
            self.cond = None
        elif kind == "SFX":
            self.cond = re.compile("(?:" + cond + ")$")
        else:
            self.cond = re.compile("^(?:" + cond + ")")

    def apply(self, word):
        if self.cond is not None and not self.cond.search(word):
            return None
        if self.kind == "SFX":
            if self.strip:
                if not word.endswith(self.strip):
                    return None
                word = word[: -len(self.strip)]
            return word + self.add
        if self.strip:
            if not word.startswith(self.strip):
                return None
            word = word[len(self.strip):]
        return self.add + word


def load_aff(path):
    affixes = defaultdict(list)  # flag -> [Affix]
    header = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if len(parts) < 4 or parts[0] not in ("PFX", "SFX"):
                continue
            kind, flag = parts[0], parts[1]
            if len(parts) == 4 and parts[2] in ("Y", "N"):
                header[flag] = parts[2] == "Y"
                continue
            add, _, cont = parts[3].partition("/")
            cond = parts[4] if len(parts) > 4 else "."
            affixes[flag].append(
                Affix(kind, flag, header.get(flag, False), parts[2], add, cont, cond)
            )
    return affixes


def _apply_suffixes(word, flags, affixes, depth=0):
    """Yield (form, cross_product_ok) for every suffix in ``flags``."""
    for flag in flags:
        for aff in affixes.get(flag, ()):
            if aff.kind != "SFX":
                continue
            form = aff.apply(word)
            if form is None:
                continue
            yield form, aff.cross
            if aff.cont and depth < 2:
                for sub, cross in _apply_suffixes(form, aff.cont, affixes, depth + 1):
                    yield sub, cross and aff.cross


def expand_entry_groups(stem, flags, affixes):
    """Return {base word: forms}: the stem with its suffixed forms, plus one
    group per prefix (en+cantador -> encantador, encantadora...), since a
    prefixed word is a different word with its own inflections."""
    groups = {stem: {stem}}
    suffixed = [(stem, True)]
    for form, cross in _apply_suffixes(stem, flags, affixes):
        groups[stem].add(form)
        suffixed.append((form, cross))
    for flag in flags:
        for aff in affixes.get(flag, ()):
            if aff.kind != "PFX":
                continue
            group = groups.setdefault(aff.add + stem[len(aff.strip):], set())
            for base, cross in suffixed:
                if base is not stem and not (cross and aff.cross):
                    continue
                form = aff.apply(base)
                if form is not None:
                    group.add(form)
    return {base: forms for base, forms in groups.items() if forms}


def expand_entry(stem, flags, affixes):
    return set().union(*expand_entry_groups(stem, flags, affixes).values())


def expand_entries(aff_path, dic_path):
    """Yield (base word, set of forms) for every dictionary entry and for
    every prefixed word derived from it."""
    affixes = load_aff(aff_path)
    with open(dic_path, encoding="utf-8") as f:
        next(f)  # first line is the entry count
        for line in f:
            fields = line.split()
            if not fields:
                continue
            stem, _, flags = fields[0].partition("/")
            yield from expand_entry_groups(stem, flags, affixes).items()


def expand(aff_path, dic_path):
    """Yield every word form generated by the dictionary."""
    for _, forms in expand_entries(aff_path, dic_path):
        yield from forms
